import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const WEB_ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../..",
);
const SKILL_REFERENCE_ROOT = path.join(
  WEB_ROOT,
  "src/ee/features/in-app-agent/skills/skills/langfuse/references",
);
const OUTPUT_PATH = path.join(
  WEB_ROOT,
  "src/ee/features/in-app-agent/server/skillIndex.generated.ts",
);

const WHITELISTED_SKILL_PATHS = [
  "error-analysis.md",
  "instrumentation.md",
  "judge-calibration.md",
];

/** @typedef {{ id: string; path: string; title: string; content: string }} Skill */
/** @typedef {{ normalizedPath: string; absolutePath: string }} ValidatedPath */

/**
 * @param {unknown} relativePath
 * @returns {ValidatedPath}
 */
export function validateWhitelistedPath(relativePath) {
  if (typeof relativePath !== "string" || relativePath.length === 0) {
    throw new Error("Whitelist entries must be non-empty strings.");
  }

  if (path.isAbsolute(relativePath)) {
    throw new Error(`Whitelist entry must be relative: ${relativePath}`);
  }

  const parts = relativePath.split(/[\\/]/);
  if (parts.includes("..")) {
    throw new Error(`Whitelist entry must not traverse directories: ${relativePath}`);
  }

  if (path.extname(relativePath) !== ".md") {
    throw new Error(`Whitelist entry must be a Markdown file: ${relativePath}`);
  }

  const normalizedPath = path.normalize(relativePath);
  const absolutePath = path.resolve(SKILL_REFERENCE_ROOT, normalizedPath);
  const relativeToRoot = path.relative(SKILL_REFERENCE_ROOT, absolutePath);

  if (relativeToRoot.startsWith("..") || path.isAbsolute(relativeToRoot)) {
    throw new Error(`Whitelist entry must stay inside skill sources: ${relativePath}`);
  }

  return { normalizedPath: normalizedPath.replaceAll(path.sep, "/"), absolutePath };
}

/**
 * @param {string} content
 * @param {string} relativePath
 */
function getTitle(content, relativePath) {
  const title = content.match(/^#\s+(.+)$/m)?.[1]?.trim();
  return title || path.basename(relativePath, ".md");
}

async function buildSkillIndexOutput() {
  /** @type {Skill[]} */
  const skills = [];

  for (const entry of WHITELISTED_SKILL_PATHS) {
    const { normalizedPath, absolutePath } = validateWhitelistedPath(entry);
    const content = await readFile(absolutePath, "utf8");
    const id = path.basename(normalizedPath, ".md");
    const title = getTitle(content, normalizedPath);
    skills.push({ id, path: normalizedPath, title, content });
  }

  return `// This file is generated by web/scripts/in-app-agent/generate-skill-index.mjs. Do not edit.\nimport type { LangfuseSkillIndexSourceData } from "./skills";\n\nexport const LANGFUSE_SKILL_INDEX = ${JSON.stringify(
    { skills },
    null,
    2,
  )} as const satisfies LangfuseSkillIndexSourceData;\n`;
}

export async function generateSkillIndex({ check = false } = {}) {
  const output = await buildSkillIndexOutput();

  if (check) {
    const existing = await readFile(OUTPUT_PATH, "utf8").catch(() => null);
    if (existing !== output) {
      throw new Error(
        `${path.relative(WEB_ROOT, OUTPUT_PATH)} is out of date. Run pnpm --filter web run skills:generate.`,
      );
    }

    console.log(`${path.relative(WEB_ROOT, OUTPUT_PATH)} is up to date.`);
    return;
  }

  await mkdir(path.dirname(OUTPUT_PATH), { recursive: true });
  await writeFile(OUTPUT_PATH, output);
  console.log(`Generated ${path.relative(WEB_ROOT, OUTPUT_PATH)}.`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await generateSkillIndex({ check: process.argv.includes("--check") });
}
